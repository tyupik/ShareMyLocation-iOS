/**
 Интерактор карты: собирает друзей, чьи локации видны текущему пользователю.

 Семантика видимости (этап 5): настройка друга активна (isEnabled) И его аудитория
 пускает текущего пользователя — allFriends, либо его uid ∈ allowedUids, либо он состоит
 в memberUids хотя бы одной группы из allowedGroupIds. Отсутствующие настройки («не шарит»),
 недоступные группы (groupNotFound) и протухшие allowedGroupIds трактованы как «не видно»;
 взаимность дружбы не проверяется — её гейтят правила чтения locations.
 Порт 1:1 из Android MapInteractor.kt.
 */
protocol MapInteractor {
    /**
     Realtime-поток видимых друзей: точки locations + имена/аватар-версии из списка друзей.
     Точки обновляются realtime-слушателем; поток также переэмитирует тиками каждые 5 секунд,
     чтобы «как давно» на экране старело без изменений данных.

     Видимость тоже realtime: настройки шаринга друзей слушаются по uid
     (SharingRepository.observeSettingsByUid), поэтому смена isEnabled/audience/allowedUids/
     allowedGroupIds у друга меняет набор видимых без перезахода на вкладку; удаление друга
     перезапускает конвейер через realtime-поток друзей. Границы realtime: состав memberUids
     групп владельца и удаление группы — одноразовый get при пересборке проекции видимости
     (документы groups/{id}, моих settings-слушателей не касаются) — обновится на следующий
     ScreenShown, видимость через allowedGroupIds остаётся по снимку на момент подписки.
     */
    func observeVisibleFriends() -> AsyncStream<[VisibleFriend]>
}
