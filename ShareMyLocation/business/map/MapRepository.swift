/**
 Контракт чтения точек геолокаций: коллекция locations в Firestore. Документ ключуется
 uid владельца; текущий пользователь подразумевается неявно.
 Порт 1:1 из Android MapRepository.kt (осознанное расхождение: realtime-чтение настроек
 шаринга друзей ушло в SharingRepository.observeSettingsByUid — слив настроек выполняет
 интерактор карты, контракт для читателя не меняется).
 */
protocol MapRepository {
    /**
     Realtime-поток точек локаций пользователей `uids`: ключ карты — uid.
     Запрос whereIn по documentId чанкуется по 10 (лимит Firestore); чанки сливаются
     в одну карту, обновление любого чанка переэмитирует объединённый результат.
     Правило чтения locations использует get(users/...), такой whereIn не provable
     (rules are not filters), поэтому отклонённый PERMISSION_DENIED чанк автоматически
     переходит на по-документные слушатели locations/{uid} — контракт от этого не меняется.
     Иная ошибка любого чанка закрывает поток — перезапуск возможен по повторной подписке
     (каждый ScreenShown); отсутствующие/запрещённые правилами документы молча
     не попадают в результат. Пустой `uids` — единичный пустой слепок без слушателей.
     */
    func observeLocationsByUids(uids: [String]) -> AsyncStream<[String: FriendLocation]>
}
